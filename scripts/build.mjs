// Dependency-free build: bundles shared + Worker code, client code, CSS and static assets into
// dist/server/index.js (the Worker entry). Usage: node scripts/build.mjs
import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { join } from 'node:path';
import vm from 'node:vm';

const root = new URL('..', import.meta.url).pathname;
const read = path => readFile(join(root, path), 'utf8');
const hash = text => createHash('sha256').update(text).digest('hex').slice(0, 10);

// Shared files are ES-module-shaped (export in front of declarations) so Node can import them in
// scripts and tests; here we strip `export` so they concatenate into one scope.
const stripExports = source => source.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|class)\b)/gm, '');

async function parts(dir, { strip = false } = {}) {
  const names = (await readdir(join(root, dir))).filter(name => name.endsWith('.js')).sort();
  const chunks = [];
  for (const name of names) {
    const source = await read(`${dir}/${name}`);
    chunks.push(`// ---- ${dir}/${name} ----\n${strip ? stripExports(source) : source}`);
  }
  return chunks.join('\n');
}

function minifyCss(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/\s*([{}:;,>])\s*/g, '$1').replace(/;}/g, '}').trim();
}

const manifest = await read('.openai/hosting.json');
const template = await read('worker/index.html');
const editorial = JSON.parse(await read('data/editorial.json'));
let legacy = '';
try { legacy = await read('private/admission-tracker.html'); }
catch (error) { if (error.code !== 'ENOENT') throw error; }

const shared = await parts('shared', { strip: true });
const clientCode = `(() => {\n'use strict';\n${shared}\n${await parts('client')}\n})();\n`;
const themeCode = await read('client/theme.boot.js.txt');
const cssFiles = (await readdir(join(root, 'styles'))).filter(name => name.endsWith('.css')).sort();
const css = minifyCss((await Promise.all(cssFiles.map(name => read(`styles/${name}`)))).join('\n'));

const names = { js: `app.${hash(clientCode)}.js`, css: `app.${hash(css)}.css`, theme: `theme.${hash(themeCode)}.js` };
const version = hash(clientCode + css + themeCode);

const html = template.replace('%%CSS%%', names.css).replace('%%JS%%', names.js).replace('%%THEME%%', names.theme);
const sw = (await read('public/sw.js')).replace(/%%VERSION%%/g, version);

const files = {};
for (const name of await readdir(join(root, 'public'))) {
  if (name === 'sw.js') continue;
  const buffer = await readFile(join(root, 'public', name));
  const type = { svg: 'image/svg+xml', png: 'image/png', webmanifest: 'application/manifest+json', txt: 'text/plain; charset=utf-8' }[name.split('.').pop()] || 'application/octet-stream';
  files['/' + name] = type.startsWith('image/svg') || type.startsWith('application/manifest') || type.startsWith('text/')
    ? { type, text: buffer.toString('utf8') } : { type, base64: buffer.toString('base64') };
}

const assets = {
  version, html, legacy, editorial, names,
  client: clientCode, css, theme: themeCode, sw, files,
};
const workerCode = `// Generated by scripts/build.mjs — do not edit.\nconst assets = ${JSON.stringify(assets)};\n${shared}\n${await parts('worker/src')}\n`;

await mkdir(join(root, 'dist/server'), { recursive: true });
await mkdir(join(root, 'dist/.openai'), { recursive: true });
await writeFile(join(root, 'dist/server/index.js'), workerCode);
await writeFile(join(root, 'dist/.openai/hosting.json'), manifest);

const syntax = spawnSync(process.execPath, ['--check', join(root, 'dist/server/index.js')], { encoding: 'utf8' });
if (syntax.status !== 0) { console.error(syntax.stderr); process.exit(1); }
try { new vm.Script(clientCode, { filename: names.js }); }
catch (error) { console.error('Client bundle syntax error:\n' + error.stack); process.exit(1); }

const kb = text => (Buffer.byteLength(text) / 1024).toFixed(1) + ' KB';
console.log(`Built v${version}: worker ${kb(workerCode)} · app.js ${kb(clientCode)} · app.css ${kb(css)}`);
